"""
Builds src/lib/local/zip-data.ts: every US ZIP code area (Census ZCTA) with its center point and the
town it mostly lies in. All three sources are US Census Bureau files (public domain):

  2023_Gaz_zcta_national.txt      https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer/2023_Gaz_zcta_national.zip
  2023_Gaz_place_national.txt     https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer/2023_Gaz_place_national.zip
  tab20_zcta520_place20_natl.txt  https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520/tab20_zcta520_place20_natl.txt

Usage:  python scripts/build-zip-data.py <folder with the three files>
The town is the Census place that covers most of the ZIP's land ("Dearborn Heights city" -> "Dearborn Heights").
"""
import csv, os, re, sys

src = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), "..", "src", "lib", "local", "zip-data.ts")


def rows(name, delim):
    with open(os.path.join(src, name), encoding="utf-8-sig", newline="") as f:
        r = csv.reader(f, delimiter=delim)
        head = [h.strip() for h in next(r)]
        for row in r:
            yield dict(zip(head, (c.strip() for c in row)))


places = {}
for p in rows("2023_Gaz_place_national.txt", "\t"):
    # Drop the legal description at the end: "city", "CDP", "village", "charter township", ...
    name = re.sub(r"\s+(city|town|village|borough|CDP|municipality|charter township|township|city and borough|urban county|consolidated government.*|metropolitan government.*|unified government.*|\(balance\))$", "", p["NAME"], flags=re.I)
    places[p["GEOID"]] = (name, p["USPS"])

best = {}
for r in rows("tab20_zcta520_place20_natl.txt", "|"):
    z, pl = r["GEOID_ZCTA5_20"], r["GEOID_PLACE_20"]
    if not z or not pl or pl not in places:
        continue
    land = int(r["AREALAND_PART"] or 0)
    if z not in best or land > best[z][0]:
        best[z] = (land, pl)

lines = []
for z in rows("2023_Gaz_zcta_national.txt", "\t"):
    zip5 = z["GEOID"]
    lat, lng = float(z["INTPTLAT"]), float(z["INTPTLONG"])
    town, st = places[best[zip5][1]] if zip5 in best else ("", "")
    lines.append(f"{zip5}|{lat:.4f}|{lng:.4f}|{town.replace('|', ' ')}|{st}")

lines.sort()
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// GENERATED by scripts/build-zip-data.py from US Census Bureau files (public domain). Do not edit.\n")
    f.write("// One line per ZIP code area (ZCTA): zip|latitude|longitude|town|state. Server only.\n")
    f.write("export const ZIP_DATA = `")
    f.write("\n".join(lines))
    f.write("`;\n")
print(len(lines), "ZIPs ->", os.path.normpath(out), os.path.getsize(out), "bytes")
